"""وضع الطوارئ: ماذا يقول المساعد حين ينقطع النموذج.

الافتراضي عند أي عطل هو التحويل لموظف — وهو الصواب، لأن التخمين أسوأ من
الصمت. لكن التحويل الكامل ثمنه باهظ في موسم الحج: انقطاع خمس دقائق يعني
عشرات الأسئلة تتكدّس على الاستقبال، وأكثرها «وش كلمة سر الواي فاي».

فبينهما طريق ثالث آمن: **الاقتباس الحرفي**. إن كان السؤال أحد الأسئلة
المعروفة، وكانت هناك حقيقة واحدة موثّقة وظاهرة تغطيه، نعيد نصها كما هو —
بلا إعادة صياغة، وبلا ترجمة، وبلا استنتاج. اقتباس نصّ مخزَّن لا يمكن أن يخترع
معلومة، لأنه لا يولّد شيئًا أصلًا.

وحدوده مرسومة بإحكام، فالوضع استثناء لا بديل:

  - لا يعمل إلا بعد فشل النموذج فعلًا.
  - لا يعمل إلا على الأسئلة الثمانية المعروفة، لا على نصّ حرّ. سؤال لم نره
    من قبل قد يعني شيئًا آخر تمامًا، والمطابقة بالكلمات تخطئ فيه.
  - مطابقة **واحدة** بالضبط. حقيقتان تغطيان السؤال تعنيان أننا لا نعرف أيهما
    أراد — فيُحوَّل.
  - لا ترجمة. نزيل كتب بالإندونيسية يأخذ النص العربي كما هو، ومعه سطر يوضح
    أن الخدمة مؤقتًا بلغة الفندق. النص الصحيح بلغة غير لغته أنفع من لا شيء،
    والترجمة بلا نموذج تخمين.
  - حقيقة مدفوعة أو لها نافذة وقت لا تُقتبس هنا: سعرها قد يتغيّر، ومعرفة أن
    المطعم «مفتوح الآن» تحتاج حسابًا لا اقتباسًا.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

# نفس مفاتيح الاختصارات في صفحة النزيل. الربط بالمفتاح لا بالنص: النص يتغيّر
# مع اللغة، والمفتاح لا يتغيّر.
SHORTCUT_TOPICS: dict[str, tuple[str, ...]] = {
    "wifi": ("wifi", "واي فاي", "الواي فاي", "انترنت", "شبكة"),
    "breakfast": ("breakfast", "إفطار", "الإفطار", "فطور"),
    "gate": ("gate", "باب", "أبواب", "الحرم", "باب الحرم"),
    "water": ("zamzam", "زمزم", "ماء"),
    "laundry": ("laundry", "غسيل", "الغسيل", "مغسلة"),
    "clean": ("housekeeping", "تنظيف", "التدبير"),
    "towels": ("housekeeping", "مناشف", "التدبير"),
}

NOTICE = {
    "ar": "",
    "other": "الخدمة مؤقتًا بلغة الفندق. الاستقبال يساعدك بلغتك.",
}


@dataclass(frozen=True)
class Quote:
    """اقتباس جاهز للإرسال، ومعه الحقيقة التي جاء منها."""

    text: str
    fact_key: str


def quote_for(shortcut: str, facts, language: str = "ar") -> Optional[Quote]:
    """الحقيقة الوحيدة التي تغطي هذا الاختصار، أو لا شيء.

    `facts` أي تسلسل من كائنات لها `key` و`topic` و`text`، وقد يكون لها
    `paid` و`hours`.
    """
    topics = SHORTCUT_TOPICS.get(shortcut)
    if not topics:
        return None

    hits = []
    for fact in facts:
        if getattr(fact, "paid", False) or getattr(fact, "hours", None):
            continue                       # سعر أو وقت — يحتاج حسابًا لا اقتباسًا
        haystack = f"{getattr(fact, 'key', '')} {getattr(fact, 'topic', '')}".lower()
        if any(t.lower() in haystack for t in topics):
            hits.append(fact)

    if len(hits) != 1:                     # صفر = لا نعرف، اثنتان = لا نعرف أيّهما
        return None

    fact = hits[0]
    text = fact.text.strip()
    if language and language != "ar":
        text = f"{text}\n\n{NOTICE['other']}"
    return Quote(text=text, fact_key=getattr(fact, "key", ""))
