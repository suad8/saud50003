class Translator:
    """مترجم مربوط بلغة واحدة، يُمرَّر للقوالب باسم `t`."""

    def __init__(self, code: str) -> None:
        self.locale = LOCALES.get(code, LOCALES[DEFAULT_LOCALE])
        self._strings = TRANSLATIONS.get(self.locale.code, {})
        self._fallback = TRANSLATIONS["en"]

    @property
    def code(self) -> str:
        return self.locale.code

    @property
    def direction(self) -> str:
        return self.locale.direction

    @property
    def font(self) -> str:
        return self.locale.font

    def __call__(self, key: str, **kwargs) -> str:
        text = self._strings.get(key) or self._fallback.get(key) or key
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError):
                return text
        return text


def get_translator(code: str | None) -> Translator:
    return Translator((code or DEFAULT_LOCALE).strip().lower())
